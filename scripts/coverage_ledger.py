#!/usr/bin/env python3
"""Generate docs/COVERAGE.md: every catalog screen (web + iOS) with route, implementation file,
primary API dependencies, tests and status. Run after changing routes or screens."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps/web/src"


def web_pages() -> dict[str, str]:
    pages: dict[str, str] = {}
    for f in [WEB / "routes.tsx", *sorted(WEB.glob("routes.group-*.tsx"))]:
        for sid, mod in re.findall(r"'(web-\d+)':\s*lazy\(\(\) => import\('\./pages/([^']+)'\)\)", f.read_text()):
            pages[sid] = f"apps/web/src/pages/{mod}.tsx"
    return pages


def endpoints(path: Path) -> list[str]:
    """Collect /v1 endpoints referenced by a page and the group components it imports."""
    files = [path]
    text = path.read_text()
    for imp in re.findall(r"from '\.\./components/(group[bcd]/[A-Za-z]+)'", text):
        files.append(WEB / "components" / f"{imp}.tsx")
    found: set[str] = set()
    for f in files:
        if f.exists():
            body = f.read_text()
            found |= set(re.findall(r"endpoints\.([a-zA-Z]+)\.", body))
            found |= {m.split("${")[0].rstrip("/") for m in re.findall(r"['`](/v1/[a-z\-/]+(?:\$\{)?)", body)}
    return sorted(found)[:6]


def main() -> None:
    screens = json.loads((ROOT / "design/screens.json").read_text())
    pages = web_pages()
    dedicated = {p.stem.replace(".test", "") for p in (WEB / "pages").glob("*.test.tsx")}
    ios_rows = {}
    for line in (ROOT / "apps/ios/COVERAGE.md").read_text().splitlines():
        m = re.match(r"\| (ios-\d+) \| [^|]+ \| ([^|]+) \|", line)
        if m:
            ios_rows[m.group(1)] = m.group(2).strip()
    out = ["# Screen coverage ledger", "",
           "Generated by `scripts/coverage_ledger.py`. Status meanings:",
           "- **Implemented · verified in browser**: page wired to the live API, rendered against the dev API in a real",
           "  browser (Playwright sweep of all signed-in routes, no error states, no failing API calls, no console errors).",
           "- **Implemented · compiled**: SwiftUI source compiled for iOS Simulator on the macOS CI runner;",
           "  not run on a simulator or device.",
           "",
           "Every web screen is additionally covered by `apps/web/src/pages/screens.smoke.test.tsx` (renders under",
           "API 500 / 403 / 503 with a visible recoverable state). Dependency-gated features show an explicit",
           "unavailable state rather than data (face SDK, behavior model, re-identification, redaction, APNs, OIDC).", "",
           "## Web (54)", "", "| ID | Screen | Route | Implementation | API | Tests | Status |", "|---|---|---|---|---|---|---|"]
    for s in screens:
        if s["platform"] != "web":
            continue
        page = pages.get(s["id"])
        key = Path(page).stem if page else None
        tests = ["smoke"] if s["id"] not in ("web-01", "web-02", "web-03") else []
        if key in dedicated:
            tests.insert(0, f"{key}.test.tsx")
        api = ", ".join(f"`{e}`" for e in endpoints(ROOT / page)) if page else ""
        status = "Implemented · verified in browser" if page else "MISSING"
        out.append(f"| {s['id']} | {s['title']['en']} / {s['title']['ja']} | `{s['route']}` | "
                   f"`{page.replace('apps/web/src/', '') if page else '—'}` | {api} | {', '.join(tests) or 'E2E sign-in'} | {status} |")
    out += ["", "## iOS (34)", "", "Details per screen (endpoints, states): `apps/ios/COVERAGE.md`.", "",
            "| ID | Screen | SwiftUI view | Status |", "|---|---|---|---|"]
    for s in screens:
        if s["platform"] != "ios":
            continue
        view = ios_rows.get(s["id"], "—")
        out.append(f"| {s['id']} | {s['title']['en']} / {s['title']['ja']} | {view} | "
                   f"{'Implemented · compiled' if view != '—' else 'MISSING'} |")
    missing = sum(1 for l in out if l.endswith("| MISSING |"))
    out.insert(2, f"**{sum(1 for s in screens if s['platform'] == 'web')} web + "
                  f"{sum(1 for s in screens if s['platform'] == 'ios')} iOS screens; missing: {missing}.**\n")
    (ROOT / "docs/COVERAGE.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/COVERAGE.md (missing {missing})")


if __name__ == "__main__":
    main()
