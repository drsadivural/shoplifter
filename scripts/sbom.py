#!/usr/bin/env python3
"""Generate docs/SBOM.md: every locked dependency with version and declared license.

Python licenses are read from the installed distribution metadata of each project's .venv
(run `uv sync` first); npm licenses from node_modules/<pkg>/package.json (run `npm ci` first).
Packages whose metadata declares no license are listed as UNKNOWN for manual review.
"""
from __future__ import annotations

import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def python_licenses(project: Path) -> dict[str, str]:
    venv_py = project / ".venv" / "bin" / "python"
    if not venv_py.exists():
        return {}
    code = r"""
import json, importlib.metadata as m
out = {}
for d in m.distributions():
    md = d.metadata
    lic = md.get("License-Expression") or ""
    if not lic:
        cls = [c.split("::")[-1].strip() for c in (md.get_all("Classifier") or []) if c.startswith("License ::")]
        lic = "; ".join(cls) or (md.get("License") or "").splitlines()[0][:80] if (cls or md.get("License")) else ""
    out[md["Name"].lower().replace("_", "-")] = lic or "UNKNOWN"
print(json.dumps(out))
"""
    return json.loads(subprocess.check_output([str(venv_py), "-I", "-c", code], text=True))


def python_section(name: str, project: Path) -> list[str]:
    lock = tomllib.loads((project / "uv.lock").read_text())
    lic = python_licenses(project)
    rows = [f"### {name} (`{project.relative_to(ROOT)}`, uv.lock)", "", "| Package | Version | License |", "|---|---|---|"]
    for p in sorted(lock["package"], key=lambda p: p["name"]):
        if p.get("source", {}).get("editable") or p.get("source", {}).get("virtual"):
            continue
        rows.append(f"| {p['name']} | {p['version']} | {lic.get(p['name'], 'UNKNOWN')} |")
    return rows + [""]


def npm_section(name: str, project: Path) -> list[str]:
    lock = json.loads((project / "package-lock.json").read_text())
    rows = [f"### {name} (`{project.relative_to(ROOT)}`, package-lock.json)", "",
            "| Package | Version | License | Scope |", "|---|---|---|---|"]
    for path, meta in sorted(lock.get("packages", {}).items()):
        if not path.startswith("node_modules/"):
            continue
        pkg = path.split("node_modules/")[-1]
        license_ = meta.get("license")
        if not license_:
            pj = project / path / "package.json"
            if pj.exists():
                license_ = json.loads(pj.read_text()).get("license")
        rows.append(f"| {pkg} | {meta.get('version', '?')} | {license_ or 'UNKNOWN'} | {'dev' if meta.get('dev') else 'runtime'} |")
    return rows + [""]


def main() -> None:
    lines = ["# Software bill of materials and license report", "",
             "Generated by `scripts/sbom.py` from the committed lockfiles. Runtime images additionally pin base images by",
             "digest (see `services/api/Dockerfile`, `infra/docker-compose.prod.yml`). No third-party model weights,",
             "datasets, face SDKs or research code (Shopformer, STG-NF) are included in this repository.", ""]
    for name, rel in (("API / worker", "services/api"), ("Edge appliance", "services/edge")):
        if (ROOT / rel / "uv.lock").exists():
            lines += python_section(name, ROOT / rel)
    if (ROOT / "apps/web/package-lock.json").exists():
        lines += npm_section("Web console", ROOT / "apps/web")
    lines += ["### iOS", "", "The iOS app and RetailGuardCore use only Apple system frameworks (SwiftUI, Foundation, Security,",
              "LocalAuthentication, UserNotifications, PhotosUI, AVFoundation, AVKit). No third-party Swift packages.", ""]
    unknown = sum(1 for l in lines if "| UNKNOWN |" in l)
    lines.insert(5, f"Packages with UNKNOWN license metadata requiring manual review: **{unknown}**.\n")
    (ROOT / "docs/SBOM.md").write_text("\n".join(lines))
    print(f"wrote docs/SBOM.md ({unknown} unknown)")


if __name__ == "__main__":
    sys.exit(main())
