#!/usr/bin/env node
// Regenerates the design-derived sources from the repository design contract:
//   design/ja.json       -> src/i18n/design-ja.generated.json (field labels + web screen titles)
//   design/screens.json  -> src/screens.generated.ts           (54 web screens)
// Run `npm run sync:design` whenever design/ changes. The output is committed and a
// unit test (src/i18n/catalog.test.ts) fails if it drifts from design/.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const app = resolve(here, '..');

const ja = JSON.parse(readFileSync(resolve(repo, 'design/ja.json'), 'utf8'));
const screens = JSON.parse(readFileSync(resolve(repo, 'design/screens.json'), 'utf8'));
const web = screens.filter((s) => s.platform === 'web');

const catalog = { ...ja };
const conflicts = [];
for (const s of web) {
  const existing = catalog[s.title.en];
  if (existing !== undefined && existing !== s.title.ja) {
    conflicts.push(`${s.id}: "${s.title.en}" design/ja.json="${existing}" screens.json="${s.title.ja}"`);
    continue; // design/ja.json wins; screen titles are rendered via screen.title directly anyway
  }
  catalog[s.title.en] = s.title.ja;
}
const sorted = Object.fromEntries(Object.entries(catalog).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
writeFileSync(resolve(app, 'src/i18n/design-ja.generated.json'), JSON.stringify(sorted, null, 2) + '\n');

const lines = [
  '// GENERATED by scripts/sync-design.mjs from design/screens.json — do not edit by hand.',
  '// Run `npm run sync:design` after changing design/screens.json.',
  '',
  'export interface ScreenDef {',
  '  readonly id: string;',
  '  readonly key: string;',
  '  readonly route: string;',
  '  readonly kind: string;',
  '  readonly title: { readonly en: string; readonly ja: string };',
  '  readonly fields: readonly string[];',
  '  readonly states: readonly string[];',
  '}',
  '',
  `export const WEB_SCREENS = ${JSON.stringify(
    web.map((s) => ({ id: s.id, key: s.key, route: s.route, kind: s.kind, title: s.title, fields: s.fields, states: s.states ?? [] })),
    null,
    2,
  )} as const satisfies readonly ScreenDef[];`,
  '',
  'export type ScreenId = (typeof WEB_SCREENS)[number][\'id\'];',
  '',
];
writeFileSync(resolve(app, 'src/screens.generated.ts'), lines.join('\n'));

console.log(`design catalog: ${Object.keys(sorted).length} keys; web screens: ${web.length}`);
if (conflicts.length) console.warn('title conflicts (design/ja.json kept):\n  ' + conflicts.join('\n  '));
